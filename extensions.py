# extensions.py
import os

from flask_migrate import Migrate
from flask_sqlalchemy import SQLAlchemy
from sqlalchemy import MetaData

# Deterministic names for every index and constraint, identical on SQLite and
# PostgreSQL. Alembic needs a name to drop or alter a constraint, and on SQLite
# (batch mode, which rebuilds the table) unnamed constraints can't be targeted
# at all. Must be in place before the baseline migration is generated.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

db = SQLAlchemy(metadata=MetaData(naming_convention=NAMING_CONVENTION))

# render_as_batch: on SQLite, autogenerated ALTERs are wrapped in
# batch_alter_table() (copy table -> recreate -> swap), since SQLite can't
# alter or drop most constraints in place. On PostgreSQL the same batch block
# just emits plain ALTER TABLE statements, so migrations stay portable.
# The directory is absolute so `flask db ...` and pytest work from any cwd.
MIGRATIONS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "migrations")
migrate = Migrate(directory=MIGRATIONS_DIR, render_as_batch=True)
